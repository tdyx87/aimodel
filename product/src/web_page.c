/* web_page.c —— Web UI 的页面（内嵌在二进制里）
 *
 * 为什么内嵌：单文件交付是这个项目的风格（一个 exe 就是全部），
 * 页面不依赖磁盘上的额外文件，也就没有「路径不对就白屏」的问题。
 *
 * 页面本身不依赖任何前端框架：原生 fetch + EventSource。
 * 状态：
 *   - 令牌从 URL 的 ?t= 取，之后放进 X-Cagent-Token 头
 *   - EventSource 订阅 /api/events（带 token 的 query，因为 EventSource
 *     不能自定义请求头，所以这里用 query 传 token，服务端两种都收）
 *   - 批准请求用按钮 → POST /api/approve
 *
 * ---- 2026-10-22 重写（界面问题：不好看 / 不自动滚动 / 滚动条不对）----
 *
 * 三个问题的**根因**（不是「调调 CSS」能解决的）：
 *
 * 1. **每个 token 一个气泡**：
 *    旧代码对每个 text 事件都 `add('assistant', d.text)`，
 *    于是模型回一句话（几十上百个 token）会变成几十个上下堆叠的方块。
 *    现在：**同一段回复合并进同一个气泡**（cur 变量），
 *    直到出现工具调用或本轮结束才开新气泡。
 *
 * 2. **滚动条属于整页而不是消息区**：
 *    旧布局里 #log 只是个普通 div，页面随内容变长。
 *    现在 body 是 100vh 的 flex 列，#log 独占剩余空间并自己滚动。
 *    **关键细节：#log 必须写 `min-height:0`** ——
 *    flex 子项默认 `min-height:auto`，内容会把容器撑破，
 *    于是 #log 根本不会滚动，滚动条又跑到整页上去了。
 *    这是 flex 布局最经典的坑。
 *
 * 3. **自动滚动只会「乱跳」**：
 *    旧代码对每个新气泡调 `scrollIntoView({block:'end'})`，
 *    它滚动的是**最近的滚动祖先**（当时是整页），而且每来一个 token 就跳一次。
 *    现在改成「用户本来就贴着底部才跟着滚」——
 *    往回看历史时不会被强行拽回底部（这是聊天 UI 的标准做法，
 *    也是「不自动滚动」这个抱怨的正确解法：不是不滚，是别乱滚）。
 *    不在底部时右下角出现「回到底部」按钮，由用户决定。
 */

