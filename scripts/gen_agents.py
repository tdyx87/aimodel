#!/usr/bin/env python3
"""从 .role-system/manifest.json 生成各客户端的 agent 注册文件。

为什么要有这个脚本：

    角色定义（.role-system/agents/*.md）是**文档**，任何客户端都不会自动发现它。
    客户端只认自己目录下的 frontmatter 文件。于是「事实源」和「可执行注册」
    必须是两份东西，且由脚本保证它们一致——否则迟早漂移成两套说法。

用法：

    python scripts/gen_agents.py            # 生成/更新
    python scripts/gen_agents.py --check    # 只校验，不一致则退出码 1（CI 用）

生成物（不要手改，会被覆盖）：

    .opencode/agents/<id>.md   OpenCode V2：description / mode / permissions
    .claude/agents/<id>.md     Claude Code：name / description / tools / model
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, ".role-system", "manifest.json")

# 生成物标记：用于识别「过期文件」与「人手写的文件」。
MARKER = "<!-- generated by scripts/gen_agents.py — 改事实源后重新生成，勿手改 -->"

TARGETS = (
    ("opencode", os.path.join(".opencode", "agents")),
    ("claude", os.path.join(".claude", "agents")),
)

# 只读角色可以跑的 git 子命令：读历史/读差异，不能改仓库。
READONLY_SHELL = ("git diff*", "git log*", "git show*", "git status*", "ctest*")

CLAUDE_TOOLS = {
    "read-only": "Read, Grep, Glob, Bash",
    "read-write": "Read, Write, Edit, Grep, Glob, Bash",
    "dispatch": "Read, Grep, Glob, Bash, Task",
}


def load_manifest():
    with open(MANIFEST, "r", encoding="utf-8") as f:
        return json.load(f)


def boundary(role):
    cap = role["capability"]
    if cap == "read-only":
        return (
            "**只读**：除审计文档外不修改任何文件。\n"
            "需要改动时，把结论与建议交回 `orchestrator`，由对应实现角色执行。\n"
            "可以运行只读命令（`git diff`/`git log`/`git show`/`git status`）取证。"
        )
    if cap == "dispatch":
        children = role.get("may_dispatch", [])
        lines = [
            "**只编排**：不直接产出业务文件。",
            "",
            "可派发的角色（其余一律拒绝）：",
        ]
        lines += ["- `%s`" % c for c in children]
        lines += [
            "",
            "按门禁顺序放行（G1 设计 → G2 合入 → G3 质量 → G4 发布），不可跳步；",
            "每个门禁至少抽检 1 份上游审计，核对「产出」与「结论」是否一致。",
        ]
        return "\n".join(lines)
    paths = role.get("paths") or []
    lines = ["**可写，但仅限以下路径**（越界请交回 `orchestrator`）：", ""]
    lines += ["- `%s`" % p for p in paths]
    return "\n".join(lines)


def body(role, audit_dir):
    return "\n".join(
        [
            MARKER,
            "",
            "你是「%s」（`%s`）。%s" % (role["title"], role["id"], role["description"]),
            "",
            "## 唯一事实源（开工前先读）",
            "",
            "- 角色完整定义：`.role-system/agents/%s.md`" % role["id"],
            "- 角色总览与移交规则：`.role-system/roles.md`",
            "- 调用与交付契约：`.role-system/invocation.md`",
            "",
            "## 边界",
            "",
            boundary(role),
            "",
            "## 交付",
            "",
            "任务结束时必须在 `%s/` 写审计：" % audit_dir,
            "",
            "`<YYYY-MM-DD>-%s-<task>.md`" % role["id"],
            "",
            "至少包含：角色/时间/任务、输入、关键决策、产出、结论、移交。",
            "缺审计视为本任务未完成，门禁不放行。",
            "",
        ]
    )


def render_opencode(role, audit_dir):
    rules = []
    # 所有角色都必须能写审计——它是交付凭证，缺了任务就不算完成。
    rules.append(("edit", "*", "deny"))
    rules.append(("edit", audit_dir + "/**", "allow"))
    if role["capability"] == "read-write":
        for p in role.get("paths") or []:
            rules.append(("edit", p, "allow"))
        rules.append(("shell", "*", "allow"))
    elif role["capability"] == "read-only":
        rules.append(("shell", "*", "ask"))
        for cmd in READONLY_SHELL:
            rules.append(("shell", cmd, "allow"))
    else:  # dispatch
        rules.append(("shell", "*", "ask"))
        rules.append(("subagent", "*", "deny"))
        for child in role.get("may_dispatch") or []:
            rules.append(("subagent", child, "allow"))

    lines = [
        "---",
        "description: %s" % json.dumps(role["description"], ensure_ascii=False),
        "mode: %s" % role.get("mode", "subagent"),
        "permissions:",
    ]
    for action, resource, effect in rules:
        lines.append("  - action: %s" % action)
        lines.append("    resource: %s" % json.dumps(resource, ensure_ascii=False))
        lines.append("    effect: %s" % effect)
    lines.append("---")
    lines.append("")
    return "\n".join(lines) + body(role, audit_dir)


def render_claude(role, audit_dir):
    lines = [
        "---",
        "name: %s" % role["id"],
        "description: %s" % json.dumps(role["description"], ensure_ascii=False),
        "tools: %s" % CLAUDE_TOOLS[role["capability"]],
        "model: inherit",
        "---",
        "",
    ]
    return "\n".join(lines) + body(role, audit_dir)


RENDERERS = {"opencode": render_opencode, "claude": render_claude}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="只校验一致性，不写文件")
    args = parser.parse_args()

    manifest = load_manifest()
    audit_dir = manifest.get("audit_dir", "product/docs/audit")
    roles = manifest["roles"]
    ids = {r["id"] for r in roles}

    problems = []
    written = 0

    for target, rel_dir in TARGETS:
        out_dir = os.path.join(ROOT, rel_dir)
        render = RENDERERS[target]

        for role in roles:
            path = os.path.join(out_dir, role["id"] + ".md")
            expected = render(role, audit_dir)
            actual = None
            if os.path.exists(path):
                with open(path, "r", encoding="utf-8", newline="") as f:
                    actual = f.read()

            if actual == expected:
                continue
            if args.check:
                state = "缺失" if actual is None else "与 manifest 不一致"
                problems.append("%s/%s.md %s" % (rel_dir.replace(os.sep, "/"), role["id"], state))
                continue

            os.makedirs(out_dir, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(expected)
            written += 1

        # 过期生成物：manifest 里已没有该角色，但文件还带着生成标记。
        if os.path.isdir(out_dir):
            for name in sorted(os.listdir(out_dir)):
                if not name.endswith(".md"):
                    continue
                rid = name[:-3]
                if rid in ids:
                    continue
                path = os.path.join(out_dir, name)
                with open(path, "r", encoding="utf-8", newline="") as f:
                    content = f.read()
                if MARKER not in content:
                    continue  # 人手写的文件不动
                if args.check:
                    problems.append("%s/%s 是过期生成物（manifest 中已无该角色）" % (
                        rel_dir.replace(os.sep, "/"), name))
                else:
                    os.remove(path)
                    written += 1

    if args.check:
        if problems:
            print("生成物与 .role-system/manifest.json 不一致：")
            for p in problems:
                print("  -", p)
            print("\n修复：python scripts/gen_agents.py")
            return 1
        print("生成物一致：%d 个角色 × %d 个客户端" % (len(roles), len(TARGETS)))
        return 0

    print("已生成/更新 %d 个文件（%d 个角色 × %d 个客户端）" % (
        written, len(roles), len(TARGETS)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
